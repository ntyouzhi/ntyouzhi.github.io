window.PEUtil = (function () {
  function deg(a) { return a * 180 / Math.PI; }
  // 三点夹角：在 b 点，a-b-c
  function angle(a, b, c) {
    if (!a || !b || !c) return null;
    var v1x = a.x - b.x, v1y = a.y - b.y, v2x = c.x - b.x, v2y = c.y - b.y;
    var m1 = Math.hypot(v1x, v1y), m2 = Math.hypot(v2x, v2y);
    if (m1 < 1e-6 || m2 < 1e-6) return null;
    var cos = (v1x * v2x + v1y * v2y) / (m1 * m2);
    cos = Math.max(-1, Math.min(1, cos));
    return deg(Math.acos(cos));
  }
  // 躯干与竖直方向的夹角：signed 与投掷同向为正（前屈），反向为负（后仰）
  function tiltFromVertical(low, high, dirX) {
    if (!low || !high) return null;
    var dx = high.x - low.x, dy = low.y - high.y;
    var a = deg(Math.atan2(Math.abs(dx), Math.max(1e-6, Math.abs(dy))));
    return { abs: a, signed: dx * dirX >= 0 ? a : -a };
  }
  function lerp(a, b, t) { return a + (b - a) * t; }
  function clamp(v, a, b) { return Math.max(a, Math.min(b, v)); }
  function norm(a) { while (a > 180) a -= 360; while (a < -180) a += 360; return a; }
  function fmt(v, d) { return (v == null || isNaN(v)) ? '—' : v.toFixed(d == null ? 0 : d); }
  return { deg: deg, angle: angle, tiltFromVertical: tiltFromVertical, lerp: lerp, clamp: clamp, norm: norm, fmt: fmt };
})();

